let currentLanguage: Language = "zh";

export function normalizeLanguage(value: unknown): Language | undefined {
  return value === "zh" || value === "en" ? value : undefined;
}

export function setI18nLanguage(language: Language): void {
  currentLanguage = language;
}

export function getI18nLanguage(): Language {
  return currentLanguage;
}

export function getDateLocale(): string {
  return currentLanguage === "en" ? "en-US" : "zh-CN";
}

export function t(key: string, vars: Vars = {}): string {
  const template: string =
    translations[currentLanguage][key as keyof typeof translations.zh] ??
    translations.zh[key as keyof typeof translations.zh] ??
    key;

  return Object.entries(vars).reduce(
    (value, [name, replacement]) => value.replaceAll(`{${name}}`, String(replacement)),
    template
  );
}
